export async function ensureDatabase() {
  if (!initializing) {
    initializing = (async () => {
      for (const ddl of SCHEMA) await query(ddl);
      await bootstrap();
    })().catch(error => { initializing = undefined; throw error; });
  }
  return initializing;
}

async function bootstrap() {
  const email = (process.env.ADMIN_EMAIL || '').trim().toLowerCase();
  const pass = process.env.ADMIN_PASSWORD || '';
  if (Boolean(email) !== Boolean(pass)) {
    throw new Error('Set both ADMIN_EMAIL and ADMIN_PASSWORD (or neither).');
  }
  if (email) {
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) throw new Error('ADMIN_EMAIL is invalid.');
    if (pass.length < 12 || !/[a-z]/i.test(pass) || !/\d/.test(pass) || /REPLACE|CHANGE_ME|EXAMPLE_PASSWORD/i.test(pass)) {
      throw new Error('ADMIN_PASSWORD must have at least 12 characters including letters and digits.');
    }
    const name = (process.env.ADMIN_NAME || 'Residence Office').trim().slice(0, 80);
    const existed = await query('SELECT id FROM users WHERE email = $1', [email]);
    if (!existed.length) {
      await query(`INSERT INTO users(name,email,password_hash,role)
        VALUES($1,$2,$3,'staff') ON CONFLICT (email) DO NOTHING`, [name,email,passwordHash(pass)]);
    }
  }
  if (process.env.SEED_SAMPLE_ROOMS === 'true') {
    for (const room of [['AG101','AG',1,4], ['AG102','AG',1,6], ['AH201','AH',2,6], ['AH202','AH',2,8]]) {
      await query(`INSERT INTO rooms(code,building,floor,capacity) VALUES($1,$2,$3,$4)
        ON CONFLICT (code) DO NOTHING`, room);
    }
  }
}
