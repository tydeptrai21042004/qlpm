let client;
let initializing;

export function sqlClient() {
  if (!process.env.DATABASE_URL) {
    const error = new Error('DATABASE_URL is missing. Configure it in Vercel environment variables.');
    error.status = 503;
    throw error;
  }
  if (!client) client = neon(process.env.DATABASE_URL);
  return client;
}

export async function query(statement, values = []) {
  return sqlClient().query(statement, values);
}

